"""Durable paper-close intents with caller routing on identified profiles.

Every operation pins one identified lot and one journal row before either
financial file changes. Replay applies the same economics under ordered locks.
No CLI, dashboard or trader caller is activated by this module alone.
"""
from contextlib import ExitStack
import copy
from datetime import datetime, timezone
import os
import json
import secrets
import math
from pathlib import Path
from uuid import UUID, uuid5

from rshelper import journal, positions
from rshelper.market import ge_tax
from rshelper.persistence import read_state, locked_state, validate_state, canonical_uuid, MAX_STATE_BYTES
from rshelper.profile import resolve_config_path
from rshelper.state_identity import (validate_manifest, activation_manifest,
                                     require_financial_authority)
from rshelper.identity_merge import canonical_record

MAX_OPERATIONS = 10_000
MAX_METADATA_BYTES = 16 * 1024
MAX_BATCHES = 1_000
MAX_BATCH_CHILDREN = 100


def _same_json(left, right):
    """Python equality aliases bool/int and int/float; persisted requests do not."""
    return json.dumps(left, sort_keys=True, allow_nan=False) == json.dumps(right, sort_keys=True, allow_nan=False)


def _same_record(left, right, kind):
    # Display aliases can be regenerated by a peer merge. Time encodings can
    # also normalize without changing the identified record's economics.
    return _same_json({key: value for key, value in canonical_record(left, kind).items() if key != 'id'},
                      {key: value for key, value in canonical_record(right, kind).items() if key != 'id'})


def _trade_matches(rows, expected):
    if not isinstance(rows, list) or len(rows) != 1:
        return False
    row = rows[0]
    if row['revision'] < expected['revision']:
        return False
    if row['tombstone'] and row['revision'] <= expected['revision']:
        return False
    if not row['tombstone'] and row['revision'] != expected['revision']:
        return False
    return _same_record({**row, 'revision': expected['revision'], 'tombstone': expected['tombstone']},
                        expected, 'trades')


def _receipt(intent, trade, replayed):
    return {**intent['receipt'], 'trade_ids': [trade['id']],
            'trade_uuids': [trade['record_uuid']], 'replayed': replayed}


def _metadata(supplied):
    defaults = {'note': 'paper', 'strategy': 'manual', 'hold_minutes': None,
                'quote_sell': None, 'entry_spread_pct': None, 'fill_guard': False,
                'market_data': {}}
    if supplied is None:
        supplied = {}
    if not isinstance(supplied, dict) or set(supplied) - set(defaults) - {'exit_config'}:
        raise ValueError('invalid realization metadata fields')
    result = {**defaults, **copy.deepcopy(supplied)}
    if 'exit_config' in result:
        from rshelper.tuning import validate_config_evidence
        validate_config_evidence(result['exit_config'])
    for field, limit in (('note', 512), ('strategy', 64)):
        if type(result[field]) is not str or len(result[field]) > limit:
            raise ValueError('invalid realization metadata text')
    for field in ('hold_minutes', 'entry_spread_pct'):
        value = result[field]
        if value is not None and (type(value) not in (int, float) or not math.isfinite(value)):
            raise ValueError('invalid realization metadata number')
    if result['hold_minutes'] is not None and result['hold_minutes'] < 0:
        raise ValueError('invalid realization hold time')
    quote = result['quote_sell']
    if quote is not None and (type(quote) is not int or quote <= 0):
        raise ValueError('invalid realization quote')
    if type(result['fill_guard']) is not bool or not isinstance(result['market_data'], dict):
        raise ValueError('invalid realization fill/provenance metadata')
    validate_state(result, 'generic', 'realization-metadata.json')
    if len(json.dumps(result, allow_nan=False).encode('utf-8')) > MAX_METADATA_BYTES:
        raise ValueError('realization metadata exceeds byte budget')
    return result


def _intent_path(profile):
    return resolve_config_path('realizations.json', profile)


def _manifest_path(profile):
    return resolve_config_path('identity-manifest.json', profile)


def _checkpoint(step):
    """Fault-injection boundary immediately after a durable persistence step."""


def _payload(data):
    kind = 'positions' if 'positions' in data else 'trades' if 'trades' in data else 'generic'
    validate_state(data, kind, 'realization-state.json')
    payload = json.dumps(data, allow_nan=False).encode('utf-8')
    if len(payload) > MAX_STATE_BYTES:
        raise ValueError('realization state exceeds byte budget')
    return payload


def _persist(path, data):
    payload = _payload(data)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    flags = os.O_RDONLY | getattr(os, 'O_DIRECTORY', 0) | getattr(os, 'O_NOFOLLOW', 0)
    directory = os.open(path.parent, flags)
    temporary = '.realization-' + secrets.token_hex(12)
    try:
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, 'O_NOFOLLOW', 0),
                     0o600, dir_fd=directory)
        with os.fdopen(fd, 'wb') as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path.name, src_dir_fd=directory, dst_dir_fd=directory)
        os.fsync(directory)
    finally:
        try:
            try:
                os.unlink(temporary, dir_fd=directory)
            except FileNotFoundError:
                pass
        finally:
            os.close(directory)


def _paths(profile):
    return (positions._positions_path(profile), journal._trades_path(profile),
            _intent_path(profile), _manifest_path(profile))


def _load_intents(path):
    if Path(path).with_name('.profile-pending.json').exists():
        from rshelper.state_transaction import recover_profile
        recover_profile(Path(path).parent)
    store = read_state(path, 'generic')
    if not store:
        try:
            Path(path).lstat()
        except FileNotFoundError:
            store = {'schema_version': 1, 'operations': {}}
    return validate_intents(store, path)


def validate_intents(store, path):
    if set(store) != {'schema_version', 'operations'} or not isinstance(store['operations'], dict):
        raise ValueError('invalid realization intent store')
    if len(store['operations']) > MAX_OPERATIONS:
        raise ValueError('realization operation budget exceeded')
    for operation, intent in store['operations'].items():
        canonical_uuid(operation)
        if not isinstance(intent, dict) or set(intent) != {'request', 'before', 'trade', 'receipt', 'done'}:
            raise ValueError('invalid realization intent')
        if any(not isinstance(intent[field], dict) for field in ('request', 'before', 'trade', 'receipt')):
            raise ValueError('invalid realization intent payload shape')
        request, before, trade, receipt = (intent[field] for field in ('request', 'before', 'trade', 'receipt'))
        if (type(intent['done']) is not bool
                or set(request) != {'lot_uid', 'qty', 'sell_price', 'operation_id', 'reason', 'metadata'}
                or request.get('operation_id') != operation):
            raise ValueError('invalid realization operation identity')
        canonical_uuid(request['lot_uid'])
        if (type(request['qty']) is not int or request['qty'] <= 0
                or type(request['sell_price']) is not int or request['sell_price'] <= 0
                or type(request['reason']) is not str or not request['reason'] or len(request['reason']) > 64):
            raise ValueError('invalid realization request')
        metadata = _metadata(request['metadata'])
        if metadata != request['metadata']:
            raise ValueError('realization metadata must be normalized')
        validate_state({'positions': [before]}, 'positions', path)
        validate_state({'trades': [trade]}, 'trades', path)
        if 'entry_config' in trade and trade['entry_config']!=before.get('entry_config'):
            raise ValueError('realization entry configuration differs from lot')
        canonical_uuid(trade.get('origin_uuid'))
        if (type(receipt.get('remaining_qty')) is not int
                or not isinstance(receipt.get('trade_ids'), list)
                or any(type(value) is not int for value in receipt['trade_ids'])):
            raise ValueError('invalid realization receipt types')
        quantity, sell = request['qty'], request['sell_price']
        tax = ge_tax(sell) * quantity
        if (before.get('record_uuid') != request['lot_uid'] or before['qty'] < quantity
                or before.get('origin_uuid') != trade.get('origin_uuid')
                or before.get('tombstone') is not False
                or trade.get('revision') != 0 or trade.get('tombstone') is not False
                or trade['qty'] != quantity or trade['buy_price'] != before['buy_price']
                or trade['sell_price'] != sell or trade['tax_paid'] != tax
                or trade['profit'] != (sell - before['buy_price']) * quantity - tax
                or trade['item_id'] != before['item_id'] or trade['name'] != before['name']
                or trade.get('closed_lot_uid') != request['lot_uid']
                or trade.get('operation_id') != operation or trade.get('exit_reason') != request['reason']
                or not _same_json({field: trade.get(field) for field in metadata}, metadata)
                or trade.get('record_uuid') != str(uuid5(UUID(trade['origin_uuid']), operation))):
            raise ValueError('realization intent economics conflict')
        expected = {'operation_id': operation, 'trade_ids': [trade['id']], 'remaining_qty': before['qty'] - quantity}
        if receipt != expected:
            raise ValueError('realization intent receipt conflict')
    return store


def _validate_origin(paths, store):
    if store['operations']:
        manifest = validate_manifest(read_state(paths[3], 'generic'))
        lineage = read_state(paths[3].with_name('identity-lineage.json'), 'generic').get('origins', {})
        for declared in lineage.values():
            validate_manifest(declared)
        allowed = {manifest['origin_uuid'], *lineage}
        if any(intent['trade']['origin_uuid'] not in allowed
               for intent in store['operations'].values()):
            raise ValueError('realization origin manifest conflict')


def _marker(intent):
    request = intent['request']
    return {'lot_uid': request['lot_uid'], 'qty': request['qty'],
            'sell_price': request['sell_price'], 'remaining_qty': intent['receipt']['remaining_qty']}


def _remaining_lot(intent):
    remaining = intent['receipt']['remaining_qty']
    return {**intent['before'], 'qty': remaining or intent['before']['qty'],
            'tombstone': not bool(remaining), 'revision': intent['before']['revision'] + 1}


def _verify_applied_lot(position_store, store, lot_uid, chain=None):
    """The retained marker alone cannot prove that consumed units stayed closed."""
    applied = position_store['realizations']
    if chain is None:
        chain = [intent for operation, intent in store['operations'].items()
                 if operation in applied and intent['request']['lot_uid'] == lot_uid]
    chain.sort(key=lambda intent: intent['before']['revision'])
    expected = chain[0]['before']
    for intent in chain:
        marker = applied[intent['request']['operation_id']]
        target = _marker(intent)
        if (not _same_record(intent['before'], expected, 'positions') or not isinstance(marker, dict)
                or set(marker) != set(target) or marker != target
                or any(type(marker[key]) is not type(value) for key, value in target.items())):
            raise ValueError('realization lot revision chain conflict')
        expected = _remaining_lot(intent)
    rows = [row for row in position_store['positions'] if row.get('record_uuid') == lot_uid]
    if len(rows) != 1 or not _same_record(rows[0], expected, 'positions'):
        raise ValueError('realization applied lot changed or resurrected')


def _apply(paths, store, operation, replayed):
    position_path, trade_path, intent_path, _ = paths
    intent = store['operations'][operation]
    request, before, trade = intent['request'], intent['before'], intent['trade']
    position_store = read_state(position_path, 'positions')
    applied = position_store.setdefault('realizations', {})
    if not isinstance(applied, dict):
        raise ValueError('invalid position realization ledger')
    marker = _marker(intent)
    if operation in applied:
        stored = applied[operation]
        if (not isinstance(stored, dict) or set(stored) != set(marker)
                or any(type(stored[field]) is not type(marker[field]) for field in marker)
                or stored != marker):
            raise ValueError('realization position receipt conflict')
        _verify_applied_lot(position_store, store, request['lot_uid'])
    else:
        if intent['done']:
            raise ValueError('completed realization position proof missing')
        matching = [row for row in position_store['positions'] if row.get('record_uuid') == request['lot_uid']]
        if len(matching) != 1 or not _same_record(matching[0], before, 'positions'):
            raise ValueError('realization position changed; recovery requires review')
    trade_store = read_state(trade_path, 'trades')
    matches = [row for row in trade_store['trades'] if row.get('record_uuid') == trade['record_uuid']]
    if matches:
        if not _trade_matches(matches, trade):
            raise ValueError('realization journal conflict')
        applied_trade = matches[0]
    else:
        if intent['done']:
            raise ValueError('completed realization journal proof missing')
        applied_trade = copy.deepcopy(trade)
        if any(row['id'] == trade['id'] for row in trade_store['trades']):
            applied_trade['id'] = max(row['id'] for row in trade_store['trades']) + 1
        trade_store['trades'].append(applied_trade)
        validate_state(trade_store, 'trades', trade_path)
        _checkpoint('before_journal')
        _persist(trade_path, trade_store)
    if intent['done']:
        return _receipt(intent, applied_trade, True)
    _checkpoint('journal')
    if operation not in applied:
        replacement = []
        for row in position_store['positions']:
            if row.get('record_uuid') != request['lot_uid']:
                replacement.append(row)
            else:
                replacement.append({**_remaining_lot(intent), 'id': row['id']})
        position_store['positions'] = replacement
        applied[operation] = marker
        validate_state(position_store, 'positions', position_path)
        _checkpoint('before_positions')
        _persist(position_path, position_store)
    _checkpoint('positions')
    intent['done'] = True
    _checkpoint('before_receipt')
    _persist(intent_path, store)
    _checkpoint('receipt')
    return _receipt(intent, applied_trade, replayed)


def verify_realization_snapshot(positions_state, trades, store):
    # Audit completed evidence once before a restart or a new operation can
    # consume restored units. Reads are bounded; no per-operation file rewrite.
    applied = positions_state.get('realizations', {})
    if not isinstance(applied, dict) or set(applied) - set(store['operations']):
        raise ValueError('invalid or unowned position realization ledger')
    by_uuid = {}
    for row in trades:
        by_uuid.setdefault(row.get('record_uuid'), []).append(row)
    chains = {}
    for operation, intent in store['operations'].items():
        if intent['done'] and (operation not in applied
                or not _trade_matches(by_uuid.get(intent['trade']['record_uuid']), intent['trade'])):
            raise ValueError('completed realization proof missing or conflicting')
        if operation in applied:
            chains.setdefault(intent['request']['lot_uid'], []).append(intent)
    for lot_uid, chain in chains.items():
        _verify_applied_lot(positions_state, store, lot_uid, chain)


def _recover(paths, store):
    verify_realization_snapshot(read_state(paths[0], 'positions'),
                                read_state(paths[1], 'trades')['trades'], store)
    receipts = []
    for operation, intent in store['operations'].items():
        if not intent['done']:
            receipts.append(_apply(paths, store, operation, True))
    return receipts


def recover_pending(profile):
    paths = _paths(profile)
    with ExitStack() as locks:
        for path in sorted(paths, key=lambda value: str(Path(value).resolve())):
            locks.enter_context(locked_state(path))
        store = _load_intents(paths[2])
        _validate_origin(paths, store)
        return _recover(paths, store)


def close_and_realize(profile, lot_uid, qty, sell_price, operation_id, reason, *, metadata=None):
    """Close an exact identified lot once; reuse requires identical economics."""
    canonical_uuid(lot_uid)
    canonical_uuid(operation_id)
    if type(qty) is not int or qty <= 0 or type(sell_price) is not int or sell_price <= 0:
        raise ValueError('quantity and sell price must be positive integers')
    if type(reason) is not str or not reason or len(reason) > 64:
        raise ValueError('invalid realization reason')
    request = {'lot_uid': lot_uid, 'qty': qty, 'sell_price': sell_price,
               'operation_id': operation_id, 'reason': reason, 'metadata': _metadata(metadata)}
    paths = _paths(profile)
    with ExitStack() as locks:
        for path in sorted(paths, key=lambda value: str(Path(value).resolve())):
            locks.enter_context(locked_state(path))
        store = _load_intents(paths[2])
        _validate_origin(paths, store)
        if operation_id in store['operations']:
            if not _same_json(store['operations'][operation_id]['request'], request):
                raise ValueError('operation ID reused with different economics')
            return _apply(paths, store, operation_id, True)
        _recover(paths, store)
        if len(store['operations']) >= MAX_OPERATIONS:
            raise ValueError('realization operation budget exceeded; receipts retained')
        manifest = validate_manifest(read_state(paths[3], 'generic'))
        state = read_state(paths[0], 'positions')
        lots = [row for row in state['positions'] if row.get('record_uuid') == lot_uid]
        if len(lots) != 1 or lots[0].get('tombstone') is not False:
            raise ValueError('exact identified lot not open; migration or ownership review required')
        lot = lots[0]
        active = _financial_activation(profile)
        if active is not None and lot['origin_uuid'] != active['origin_uuid']:
            raise ValueError('financial close must run on the lot authority')
        if qty > lot['qty'] or lot['revision'] >= 2**63 - 1:
            raise ValueError('insufficient open quantity or exhausted lot revision')
        trade_state = read_state(paths[1], 'trades')
        trades = trade_state['trades']
        tax = ge_tax(sell_price) * qty
        trade_id = max((row['id'] for row in trades), default=0) + 1
        trade = {'id': trade_id, 'item_id': lot['item_id'], 'name': lot['name'],
                 'qty': qty, 'buy_price': lot['buy_price'], 'sell_price': sell_price,
                 'tax_paid': tax, 'profit': (sell_price - lot['buy_price']) * qty - tax,
                 'timestamp': datetime.now(timezone.utc).isoformat(), **request['metadata'],
                 'exit_reason': reason,
                 'record_uuid': str(uuid5(UUID(manifest['origin_uuid']), operation_id)),
                 'origin_uuid': manifest['origin_uuid'], 'revision': 0, 'tombstone': False,
                 'operation_id': operation_id, 'closed_lot_uid': lot_uid}
        from rshelper.tuning import config_evidence
        trade['entry_config']=copy.deepcopy(lot.get('entry_config'))
        trade['exit_config']=copy.deepcopy(request['metadata']['exit_config']) if 'exit_config' in request['metadata'] else config_evidence(profile)
        receipt = {'operation_id': operation_id, 'trade_ids': [trade_id],
                   'remaining_qty': lot['qty'] - qty}
        if any(row.get('record_uuid') == trade['record_uuid'] for row in trades):
            raise ValueError('unowned realization journal identity already exists')
        store['operations'][operation_id] = {'request': request, 'before': copy.deepcopy(lot),
                                            'trade': trade, 'receipt': receipt, 'done': False}
        # Do not publish an intent that predictable schema/size conflicts can
        # never apply. I/O failures after publication remain restart-recoverable.
        projected = store['operations'][operation_id]
        trade_state['trades'].append(trade)
        validate_state(trade_state, 'trades', paths[1])
        _payload(trade_state)
        state['positions'] = [row for row in state['positions'] if row.get('record_uuid') != lot_uid]
        state['positions'].append(_remaining_lot(projected))
        state.setdefault('realizations', {})[operation_id] = _marker(projected)
        validate_state(state, 'positions', paths[0])
        _payload(state)
        _checkpoint('before_intent')
        _persist(paths[2], store)
        _checkpoint('intent')
        return _apply(paths, store, operation_id, False)


def _financial_activation(profile):
    """Shared caller gate: legacy profiles keep the FIFO writers unchanged."""
    path = _manifest_path(profile).with_name('identity-activation.json')
    manifest = activation_manifest(path)
    if manifest is None:
        return None
    require_financial_authority(manifest)
    lineage = validate_manifest(read_state(_manifest_path(profile), 'generic'))
    if lineage['origin_uuid'] != manifest['origin_uuid']:
        raise ValueError('activation origin differs from identity manifest')
    return manifest


def new_operation_id(origin_uuid, kind, entity_id):
    """Deterministic caller operation UUID; collision-checked before pinning."""
    from uuid import UUID as _UUID
    canonical_uuid(origin_uuid)
    child = str(uuid5(_UUID(origin_uuid), kind + ':' + str(entity_id)))
    return child


def _batch_paths(profile):
    return _manifest_path(profile).with_name('realization-batches.json')


def _load_batches(path):
    try:
        data = read_state(path, 'generic')
    except FileNotFoundError:
        return {'schema_version': 1, 'batches': {}}
    if not data:
        data = {'schema_version': 1, 'batches': {}}
    return validate_batches(data)


def validate_batches(data):
    if (not isinstance(data, dict) or set(data) != {'schema_version', 'batches'}
            or type(data['schema_version']) is not int or data['schema_version'] != 1
            or not isinstance(data['batches'], dict)):
        raise ValueError('invalid realization batch store')
    if len(data['batches']) > MAX_BATCHES:
        raise ValueError('realization batch budget exceeded')
    for key, batch in data['batches'].items():
        canonical_uuid(key)
        if (not isinstance(batch, dict)
                or set(batch) != {'operations', 'legs', 'item_id', 'qty'}
                or type(batch['item_id']) is not int or batch['item_id'] <= 0
                or type(batch['qty']) is not int or batch['qty'] <= 0
                or not isinstance(batch['operations'], list)
                or not batch['operations']
                or len(batch['operations']) > MAX_BATCH_CHILDREN
                or len(set(batch['operations'])) != len(batch['operations'])
                or not isinstance(batch['legs'], dict)):
            raise ValueError('invalid realization batch')
        for operation in batch['operations']:
            canonical_uuid(operation)
        if (not batch['legs'] or set(batch['legs']) - {'traditional', 'arbitrage'}
                or any(type(price) is not int or price <= 0 for price in batch['legs'].values())):
            raise ValueError('invalid pinned batch quotes')
    return data


def _persist_batches(path, data):
    validate_batches(data)
    _persist(path, data)


def _batch_lock(path):
    return locked_state(path)


def _batch_operation_id(parent, lot_uid):
    return str(uuid5(UUID(parent), 'close:' + lot_uid))


def prepare_close_batch(profile, item_id, qty, operation_id, quotes, *,
                        lot_uids=None, reason='manual', metadata=None):
    """Pin exact lot children for one close before any financial file moves."""
    canonical_uuid(operation_id)
    manifest = _financial_activation(profile)
    if manifest is None:
        raise ValueError('prepare_close_batch requires an identified profile')
    if type(item_id) is not int or item_id <= 0:
        raise ValueError('item id must be a positive integer')
    if type(qty) is not int or qty <= 0:
        raise ValueError('quantity must be a positive integer')
    if not isinstance(quotes, dict) or not quotes:
        raise ValueError('quotes must map at least one direction to a price')
    legs = {}
    for direction, price in quotes.items():
        if direction not in ('traditional', 'arbitrage'):
            raise ValueError('unknown quote direction ' + str(direction))
        if type(price) is not int or price <= 0:
            raise ValueError('quote price must be a positive integer')
        legs[direction] = price
    normalized = _metadata(metadata)
    if type(reason) is not str or not reason or len(reason) > 64:
        raise ValueError('invalid realization reason')
    paths = _paths(profile)
    batch_path = _batch_paths(profile)
    with ExitStack() as locks:
        for path in sorted(paths + (batch_path,), key=lambda value: str(Path(value).resolve())):
            locks.enter_context(locked_state(path))
        store = _load_intents(paths[2])
        _validate_origin(paths, store)
        batches = _load_batches(batch_path)
        if operation_id in batches['batches']:
            pinned = batches['batches'][operation_id]
            if (pinned['item_id'] != item_id or pinned['qty'] != qty
                    or pinned['legs'] != legs):
                raise ValueError('operation ID reused with different economics')
            children = []
            for child_id in pinned['operations']:
                intent = store['operations'].get(child_id)
                if intent is None:
                    raise ValueError('pinned batch child missing; recovery required')
                request = intent['request']
                children.append({'operation_id': child_id,
                                 'lot_uid': request['lot_uid'],
                                 'qty': request['qty'],
                                 'buy_price': intent['before']['buy_price'],
                                 'sell_price': request['sell_price'],
                                 'reason': request['reason']})
            return {'operation_id': operation_id, 'operations': children,
                    'item_id': item_id, 'qty': qty}
        _recover(paths, store)
        if len(store['operations']) >= MAX_OPERATIONS:
            raise ValueError('realization operation budget exceeded; receipts retained')
        if len(batches['batches']) >= MAX_BATCHES:
            raise ValueError('realization batch budget exceeded')
        state = read_state(paths[0], 'positions')
        open_lots = [row for row in state['positions']
                     if row.get('tombstone') is False and row.get('item_id') == item_id]
        if lot_uids is not None:
            if (not isinstance(lot_uids, list)
                    or any(not isinstance(value, str) for value in lot_uids)
                    or len(set(lot_uids)) != len(lot_uids)):
                raise ValueError('lot_uids must be a list of distinct strings')
            selected = set(lot_uids)
            open_lots = [row for row in open_lots if row.get('lot_uid') in selected]
            if len(open_lots) != len(selected):
                raise ValueError('exact identified lot not open; migration or ownership review required')
        open_lots.sort(key=lambda row: row['id'])
        if sum(row['qty'] for row in open_lots) < qty:
            raise ValueError('insufficient open quantity for batch close')
        remaining = qty
        children = []
        trades_state = read_state(paths[1], 'trades')
        next_trade_id = max((row['id'] for row in trades_state['trades']), default=0) + 1
        for lot in open_lots:
            if remaining <= 0:
                break
            if lot['revision'] >= 2**63 - 1:
                raise ValueError('exhausted lot revision')
            if lot['origin_uuid'] != manifest['origin_uuid']:
                raise ValueError('financial close must run on the lot authority')
            take = min(remaining, lot['qty'])
            direction = lot.get('direction', 'traditional')
            if direction not in legs:
                raise ValueError('missing quote for lot direction ' + str(direction))
            sell = legs[direction]
            child = _batch_operation_id(operation_id, lot['lot_uid'])
            if child in store['operations']:
                raise ValueError('realization operation identity already pinned')
            tax = ge_tax(sell) * take
            trade = {'id': next_trade_id, 'item_id': lot['item_id'], 'name': lot['name'],
                     'qty': take, 'buy_price': lot['buy_price'], 'sell_price': sell,
                     'tax_paid': tax, 'profit': (sell - lot['buy_price']) * take - tax,
                     'timestamp': datetime.now(timezone.utc).isoformat(),
                     'note': normalized['note'], 'strategy': normalized['strategy'],
                     'hold_minutes': normalized['hold_minutes'],
                     'quote_sell': normalized['quote_sell'],
                     'entry_spread_pct': normalized['entry_spread_pct'],
                     'fill_guard': normalized['fill_guard'],
                     'market_data': normalized['market_data'],
                     'exit_reason': reason,
                     'record_uuid': str(uuid5(UUID(manifest['origin_uuid']), child)),
                     'origin_uuid': manifest['origin_uuid'], 'revision': 0,
                     'tombstone': False, 'operation_id': child,
                     'closed_lot_uid': lot['lot_uid']}
            from rshelper.tuning import config_evidence
            trade['entry_config']=copy.deepcopy(lot.get('entry_config'))
            trade['exit_config']=copy.deepcopy(normalized['exit_config']) if 'exit_config' in normalized else config_evidence(profile)
            receipt = {'operation_id': child, 'trade_ids': [next_trade_id],
                       'remaining_qty': lot['qty'] - take}
            if any(row.get('record_uuid') == trade['record_uuid']
                   for row in trades_state['trades']):
                raise ValueError('unowned realization journal identity already exists')
            request = {'lot_uid': lot['lot_uid'], 'qty': take, 'sell_price': sell,
                       'operation_id': child, 'reason': reason, 'metadata': normalized}
            store['operations'][child] = {'request': request, 'before': copy.deepcopy(lot),
                                          'trade': trade, 'receipt': receipt, 'done': False}
            projected = store['operations'][child]
            trial_trades = copy.deepcopy(trades_state)
            trial_trades['trades'].append(trade)
            validate_state(trial_trades, 'trades', paths[1])
            _payload(trial_trades)
            trial_positions = copy.deepcopy(state)
            trial_positions['positions'] = [row for row in state['positions']
                                            if row.get('record_uuid') != lot['lot_uid']]
            trial_positions['positions'].append(_remaining_lot(projected))
            trial_positions.setdefault('realizations', {})[child] = _marker(projected)
            validate_state(trial_positions, 'positions', paths[0])
            _payload(trial_positions)
            children.append({'operation_id': child, 'lot_uid': lot['lot_uid'],
                             'qty': take, 'buy_price': lot['buy_price'],
                             'sell_price': sell, 'reason': reason})
            next_trade_id += 1
            remaining -= take
        batches['batches'][operation_id] = {
            'operations': [child['operation_id'] for child in children],
            'legs': legs, 'item_id': item_id, 'qty': qty}
        _persist(paths[2], store)
        _persist_batches(batch_path, batches)
        return {'operation_id': operation_id, 'operations': children,
                'item_id': item_id, 'qty': qty}


def realize_close_batch(profile, operation_id):
    """Apply one pinned batch once; retries replay the pinned economics."""
    canonical_uuid(operation_id)
    if _financial_activation(profile) is None:
        raise ValueError('realize_close_batch requires an identified profile')
    paths = _paths(profile)
    batch_path = _batch_paths(profile)
    with ExitStack() as locks:
        for path in sorted(paths + (batch_path,), key=lambda value: str(Path(value).resolve())):
            locks.enter_context(locked_state(path))
        store = _load_intents(paths[2])
        _validate_origin(paths, store)
        batches = _load_batches(batch_path)
        pinned = batches['batches'].get(operation_id)
        if pinned is None:
            raise ValueError('unknown realization batch operation')
        if any(child not in store['operations'] for child in pinned['operations']):
            raise ValueError('pinned batch children missing; recovery required')
        receipts = []
        for child in pinned['operations']:
            intent = store['operations'][child]
            receipts.append(_apply(paths, store, child, bool(intent['done'])))
        return {'operation_id': operation_id, 'receipts': receipts}


def batch_summary(profile, operation_id):
    """Read one pinned batch's economics without requiring live lots."""
    canonical_uuid(operation_id)
    if _financial_activation(profile) is None:
        raise ValueError('batch_summary requires an identified profile')
    batch_path = _batch_paths(profile)
    paths = _paths(profile)
    with ExitStack() as locks:
        for path in sorted(paths + (batch_path,), key=lambda value: str(Path(value).resolve())):
            locks.enter_context(locked_state(path))
        store = _load_intents(paths[2])
        batches = _load_batches(batch_path)
        _validate_origin(paths, store)
        pinned = batches['batches'].get(operation_id)
        if pinned is None:
            raise ValueError('unknown realization batch operation')
        children = []
        for child_id in pinned['operations']:
            intent = store['operations'].get(child_id)
            if intent is None:
                raise ValueError('pinned batch child missing; recovery required')
            request = intent['request']
            children.append({'operation_id': child_id,
                             'lot_uid': request['lot_uid'],
                             'name': intent['before']['name'],
                             'qty': request['qty'],
                             'buy_price': intent['before']['buy_price'],
                             'sell_price': request['sell_price'],
                             'reason': request['reason']})
        return {'operation_id': operation_id, 'operations': children,
                'item_id': pinned['item_id'], 'qty': pinned['qty']}
